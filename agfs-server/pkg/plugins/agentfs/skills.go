package agentfs

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/sirupsen/logrus"
	"gopkg.in/yaml.v3"
)

// DefaultSkillTTL is used when a skill does not specify a ttl.
const DefaultSkillTTL = 5 * time.Minute

const maxSkillFiles = 32

var (
	skillNameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,63}$`)
	skillFileRe = regexp.MustCompile(`^(-\s*)?([A-Za-z0-9][A-Za-z0-9._-]*\.[A-Za-z0-9]{1,8})\s*(?:—|–|:|-)\s*(.+)$`)
	skillBareRe = regexp.MustCompile(`^(-\s*)?([A-Za-z0-9][A-Za-z0-9._-]*\.[A-Za-z0-9]{1,8})\s*$`)
)

// SkillFile is a file declared in the skill's "Files" section.
type SkillFile struct {
	Name        string
	Description string
}

// Skill is a parsed SKILL.md document.
type Skill struct {
	Name        string
	FileName    string
	Description string
	TTL         time.Duration
	Keywords    []string
	Body        string
	Files       []SkillFile
	Raw         []byte
	LoadedAt    time.Time
}

type skillFrontmatter struct {
	Name        string   `yaml:"name"`
	Description string   `yaml:"description"`
	TTL         string   `yaml:"ttl"`
	Keywords    []string `yaml:"keywords"`
}

// ParseSkill parses raw SKILL.md bytes (YAML frontmatter + markdown body).
func ParseSkill(fileName string, raw []byte) (*Skill, error) {
	text := strings.TrimPrefix(string(raw), "\ufeff")
	lines := strings.Split(text, "\n")
	if len(lines) == 0 || strings.TrimSpace(lines[0]) != "---" {
		return nil, fmt.Errorf("SKILL.md must start with a YAML frontmatter block (---)")
	}
	end := -1
	for i := 1; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) == "---" {
			end = i
			break
		}
	}
	if end < 0 {
		return nil, fmt.Errorf("unterminated YAML frontmatter (missing closing ---)")
	}
	var fm skillFrontmatter
	if err := yaml.Unmarshal([]byte(strings.Join(lines[1:end], "\n")), &fm); err != nil {
		return nil, fmt.Errorf("invalid frontmatter YAML: %w", err)
	}
	if fm.Name == "" {
		return nil, fmt.Errorf("frontmatter field 'name' is required")
	}
	if !skillNameRe.MatchString(fm.Name) {
		return nil, fmt.Errorf("invalid skill name %q: must match %s", fm.Name, skillNameRe.String())
	}
	expected := fm.Name + ".md"
	if fileName != "" && fileName != expected {
		return nil, fmt.Errorf("skill file must be named %q to match frontmatter name %q", expected, fm.Name)
	}
	ttl := DefaultSkillTTL
	if fm.TTL != "" {
		d, err := time.ParseDuration(fm.TTL)
		if err != nil || d <= 0 {
			return nil, fmt.Errorf("invalid ttl %q: use a Go duration like 5m or 1h", fm.TTL)
		}
		ttl = d
	}
	body := strings.Join(lines[end+1:], "\n")
	return &Skill{
		Name:        fm.Name,
		FileName:    expected,
		Description: strings.TrimSpace(fm.Description),
		TTL:         ttl,
		Keywords:    fm.Keywords,
		Body:        body,
		Files:       parseSkillFiles(body),
		Raw:         append([]byte(nil), raw...),
		LoadedAt:    time.Now(),
	}, nil
}

// parseSkillFiles extracts the declared file list from a "## Файлы" or
// "## Files" section of the skill body.
func parseSkillFiles(body string) []SkillFile {
	var files []SkillFile
	seen := map[string]bool{}
	inSection := false
	for _, line := range strings.Split(body, "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "## ") {
			title := strings.ToLower(strings.TrimSpace(strings.TrimPrefix(t, "## ")))
			inSection = title == "файлы" || title == "files"
			continue
		}
		if strings.HasPrefix(t, "#") {
			inSection = false
			continue
		}
		if !inSection || t == "" {
			continue
		}
		var name, desc string
		if m := skillFileRe.FindStringSubmatch(t); m != nil {
			name, desc = m[2], strings.TrimSpace(m[3])
		} else if m := skillBareRe.FindStringSubmatch(t); m != nil {
			name = m[2]
		} else {
			continue
		}
		if seen[name] {
			continue
		}
		seen[name] = true
		files = append(files, SkillFile{Name: name, Description: desc})
		if len(files) >= maxSkillFiles {
			break
		}
	}
	return files
}

// RenderSkillReadme builds the README.md shown inside the skill directory.
func RenderSkillReadme(sk *Skill) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Skill: %s\n\n%s\n\n", sk.Name, sk.Description)
	fmt.Fprintf(&b, "- TTL: %s\n", sk.TTL)
	if len(sk.Keywords) > 0 {
		fmt.Fprintf(&b, "- Keywords: %s\n", strings.Join(sk.Keywords, ", "))
	}
	if len(sk.Files) > 0 {
		b.WriteString("\n## Files\n\n")
		for _, f := range sk.Files {
			if f.Description != "" {
				fmt.Fprintf(&b, "- %s — %s\n", f.Name, f.Description)
			} else {
				fmt.Fprintf(&b, "- %s\n", f.Name)
			}
		}
	}
	b.WriteString("\nAny other path under this directory is generated by the agent on first read and cached for the TTL.\n")
	return b.String()
}

// SkillRegistry holds parsed skills keyed by skill name.
type SkillRegistry struct {
	mu     sync.RWMutex
	skills map[string]*Skill
}

func NewSkillRegistry() *SkillRegistry {
	return &SkillRegistry{skills: map[string]*Skill{}}
}

func (r *SkillRegistry) Put(sk *Skill) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.skills[sk.Name] = sk
}

func (r *SkillRegistry) Get(name string) *Skill {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return r.skills[name]
}

func (r *SkillRegistry) Remove(fileName string) bool {
	name := strings.TrimSuffix(fileName, ".md")
	r.mu.Lock()
	defer r.mu.Unlock()
	if _, ok := r.skills[name]; !ok {
		return false
	}
	delete(r.skills, name)
	return true
}

func (r *SkillRegistry) List() []*Skill {
	r.mu.RLock()
	defer r.mu.RUnlock()
	out := make([]*Skill, 0, len(r.skills))
	for _, sk := range r.skills {
		out = append(out, sk)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func (r *SkillRegistry) Len() int {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return len(r.skills)
}

// LoadFromDir preloads *.md skills from a host directory.
func (r *SkillRegistry) LoadFromDir(dir string) (int, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return 0, fmt.Errorf("cannot read skills dir %s: %w", dir, err)
	}
	loaded := 0
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			continue
		}
		sk, err := ParseSkill(e.Name(), raw)
		if err != nil {
			logrus.Warnf("[agentfs] skipping skill file %s: %v", e.Name(), err)
			continue
		}
		r.Put(sk)
		loaded++
	}
	return loaded, nil
}
